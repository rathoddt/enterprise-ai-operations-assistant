
from io import BytesIO

import pytest
from docx import Document
from pypdf import PdfWriter

from app.rag.document_loader import DocumentLoader


@pytest.fixture
def loader():
    return DocumentLoader()


def test_load_txt(loader):
    content = b"Enterprise AI Operations Assistant"
    result = loader.load_bytes("sample.txt", content)

    assert len(result) == 1
    assert result[0]["text"] == "Enterprise AI Operations Assistant"
    assert result[0]["page_number"] is None


def test_load_markdown(loader):
    content = b"# RAG Knowledge\n\nGenerated by an AI agent."
    result = loader.load_bytes("knowledge.md", content)

    assert len(result) == 1
    assert "# RAG Knowledge" in result[0]["text"]
    assert "Generated by an AI agent." in result[0]["text"]


def test_load_docx(loader):
    document = Document()
    document.add_paragraph("Enterprise AI Operations Assistant")

    table = document.add_table(rows=1, cols=2)
    table.cell(0, 0).text = "Component"
    table.cell(0, 1).text = "FastAPI"

    buffer = BytesIO()
    document.save(buffer)

    result = loader.load_bytes("sample.docx", buffer.getvalue())

    assert len(result) == 1
    assert "Enterprise AI Operations Assistant" in result[0]["text"]
    assert "Component | FastAPI" in result[0]["text"]


def test_empty_text_file_raises_error(loader):
    with pytest.raises(ValueError, match="no text"):
        loader.load_bytes("empty.txt", b"   ")


def test_unsupported_file_type_raises_error(loader):
    with pytest.raises(ValueError, match="Unsupported"):
        loader.load_bytes("sample.xlsx", b"some content")


def test_empty_pdf_raises_error(loader):
    writer = PdfWriter()
    writer.add_blank_page(width=200, height=200)

    buffer = BytesIO()
    writer.write(buffer)

    with pytest.raises(ValueError, match="No extractable text"):
        loader.load_bytes("empty.pdf", buffer.getvalue())
